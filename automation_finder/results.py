"""Writes results/RESULTS.md from the stored evaluation files, so the published numbers are reproducible."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

NAMES = {
    "tfidf": "automation-finder, TF-IDF similarity (no model)",
    "gemini": "automation-finder, Gemini embeddings",
    "keyword_baseline": "Baseline: top-10 keyword counts",
    "repeat_baseline": "Baseline: top-10 exact repeats",
}
PATTERNS = {
    "P1": "Supplier invoices re-typed into accounts",
    "P2": "Weekly timesheet chasing",
    "P3": "Quote requests copied into the CRM",
    "P4": "Reschedule requests (worded many ways)",
    "P5": "Monthly KPI report",
    "P6": "Purchase-order approvals",
    "P7": "Daily reminder calls",
    "P8": "Finished jobs invoiced by hand",
}


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def write_results(folder: Path) -> Path:
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python -m automation_finder eval` and `eval-proposals`; method in docs/evaluation.md.",
        "",
    ]
    ev_path = folder / "eval.json"
    if ev_path.exists():
        ev: dict[str, Any] = json.loads(ev_path.read_text())
        seeds = ev["seeds"]
        lines += [
            f"## Finding the planted patterns (seeds {seeds[0]}-{seeds[-1]}, 8 planted patterns each)",
            "",
            "| Method | Pattern recall | Precision | Top-5 precision | Event recall | Reschedule-request coverage "
            "| Hours error (MAPE) | Distractors reported |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for method, s in ev["summary"].items():
            lines.append(
                f"| {NAMES.get(method, method)} | {_pct(s['recall_mean'])} | {_pct(s['precision_mean'])} | "
                f"{_pct(s['top5_precision_mean'])} | {_pct(s['event_recall_mean'])} | "
                f"{_pct(s['p4_coverage_mean'])} | "
                f"{_pct(s['hours_mape_mean'])} | {s['distractor_hits']} |"
            )
        lines += [
            "",
            "Times each planted pattern was found, out of the seeds:",
            "",
            "| Pattern | " + " | ".join(NAMES.get(m, m) for m in ev["summary"]) + " |",
            "|---|" + "---:|" * len(ev["summary"]),
        ]
        for pid, name in PATTERNS.items():
            cells = [f"{s['found_in_seeds'][pid]}/{len(seeds)}" for s in ev["summary"].values()]
            lines.append(f"| {pid} {name} | " + " | ".join(cells) + " |")
        first = ev["per_seed"][0]
        best = "gemini" if "gemini" in first else "tfidf"
        lines += [
            "",
            f"Estimated vs planted hours per month, seed {first['seed']} ({NAMES[best]}):",
            "",
            "| Pattern | Estimated | Planted truth |",
            "|---|---:|---:|",
        ]
        for pid, (est, truth) in sorted(first[best]["hours"].items()):
            lines.append(f"| {pid} {PATTERNS[pid]} | {est:.1f} | {truth:.1f} |")
    hard_path = folder / "eval-hard.json"
    if hard_path.exists():
        hard: dict[str, Any] = json.loads(hard_path.read_text())
        lines += [
            "",
            "## Harder data (same seeds: half the volume, 60% of copies typed in on time, routines "
            "starting up to an hour earlier or later)",
            "",
            "| Method | Pattern recall | Precision | Top-5 precision | Event recall | Hours error (MAPE) |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for method, s in hard["summary"].items():
            lines.append(
                f"| {NAMES.get(method, method)} | {_pct(s['recall_mean'])} | {_pct(s['precision_mean'])} | "
                f"{_pct(s['top5_precision_mean'])} | {_pct(s['event_recall_mean'])} | "
                f"{_pct(s['hours_mape_mean'])} |"
            )
        lines += [
            "",
            "Times each planted pattern was found on the harder data:",
            "",
            "| Pattern | " + " | ".join(NAMES.get(m, m) for m in hard["summary"]) + " |",
            "|---|" + "---:|" * len(hard["summary"]),
        ]
        for pid, pname in PATTERNS.items():
            cells = [f"{s['found_in_seeds'][pid]}/{len(hard['seeds'])}" for s in hard["summary"].values()]
            lines.append(f"| {pid} {pname} | " + " | ".join(cells) + " |")
    pr_path = folder / "proposals.json"
    if pr_path.exists():
        pr: dict[str, Any] = json.loads(pr_path.read_text())
        lines += [
            "",
            f"## Proposal quality (rubric, {pr['items']} found patterns over seeds "
            f"{pr['seeds'][0]}-{pr['seeds'][-1]}; model answers used: {pr['model_answers_used']})",
            "",
            "| Writer | Overall | Trigger | Systems | Approval | Risk | Key steps |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        names = {
            "rules": "Rule-based writer",
            "model": "Gemini, raw answer",
            "model_guarded": "Gemini + safety rules (what the app uses)",
        }
        for method, s in pr["summary"].items():
            if s["score"] is None:
                continue
            lines.append(
                f"| {names[method]} | {_pct(s['score'])} | {_pct(s['trigger'])} | {_pct(s['systems'])} | "
                f"{_pct(s['approval'])} | {_pct(s['risk'])} | {_pct(s['key_steps'])} |"
            )
    n8n_path = folder / "n8n-import.json"
    if n8n_path.exists():
        n8n: dict[str, Any] = json.loads(n8n_path.read_text())
        ok = sum(w["imported"] for w in n8n.get("workflows", []))
        lines += [
            "",
            "## n8n test import",
            "",
            f"{ok} of {len(n8n.get('workflows', []))} generated workflows imported into n8n "
            f"{n8n.get('n8n_version', '')} and exported back with every node intact.",
        ]
    out = folder / "RESULTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
